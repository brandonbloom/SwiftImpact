import Foundation

/// The toolchain, platform, and configuration a case runs in.
public struct Environment: Sendable {
    public let id: String

    /// The environment the `swift` on `PATH` builds for.
    public static func current() throws -> Environment {
        let version = try command("swift", "--version", in: FileManager.default.temporaryDirectory)
        let build =
            version.firstMatch(of: /swiftlang-([0-9.]+)/)?.1
            ?? version.firstMatch(of: /Swift version ([0-9.]+)/)?.1 ?? "unknown"
        return Environment(id: "macos-swift-\(build)-debug")
    }
}

/// The results of every case in one environment, as `Conformance/Results/<environment>.json`.
public struct Results: Codable, Sendable {
    public var cases: [String: CaseResult] = [:]

    public init() {}

    public init(contentsOf url: URL) throws {
        self = try JSONDecoder().decode(Results.self, from: Data(contentsOf: url))
    }

    public func write(to url: URL) throws {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try (encoder.encode(self) + Data("\n".utf8)).write(to: url)
    }
}

/// How a case fared in one mode, given what its manifest expects.
public struct Verdict: Sendable {
    /// Units that escaped selection and aren't known to.
    public var escapes: [String] = []
    /// Units known to escape that escaped.
    public var knownEscapes: [String] = []
    /// Units known to escape that didn't: the gap closed, so the manifest is stale.
    public var stale: [String] = []
    public var changed = 0
    public var selected = 0
    public var units = 0

    public var passed: Bool { escapes.isEmpty && stale.isEmpty }

    public init(_ results: [UnitResult], mode: Mode, manifest: Case.Manifest) {
        let known = Set(
            (manifest.knownEscapes ?? []).filter { $0.modes?.contains(mode) ?? true }.map(\.unit))
        for result in results {
            if result.escaped {
                if known.contains(result.unit) {
                    knownEscapes.append(result.unit)
                } else {
                    escapes.append(result.unit)
                }
            } else if known.contains(result.unit) {
                stale.append(result.unit)
            }
            if result.changed { changed += 1 }
            if result.selected { selected += 1 }
        }
        units = results.count
    }

    /// A table cell: the outcome, then units changed / selected / total.
    var cell: String {
        let counts = "\(changed)/\(selected)/\(units)"
        if !escapes.isEmpty { return "❌ \(counts), escaped: \(escapes.joined(separator: ", "))" }
        if !stale.isEmpty {
            return "❗ \(counts), no longer escaped: \(stale.joined(separator: ", "))"
        }
        if !knownEscapes.isEmpty { return "⚠️ \(counts), known gap" }
        return "✅ \(counts)"
    }
}

/// The compatibility table: a row per case, a column per environment and mode.
public func compatibilityTable(cases: [Case], results: [String: Results]) -> String {
    let environments = results.keys.sorted()
    var header = "| Case | Edit |"
    var rule = "|---|---|"
    for environment in environments {
        for mode in Mode.allCases {
            header += " \(environment), \(mode.rawValue) |"
            rule += "---|"
        }
    }
    var lines = [
        "# Compatibility",
        "",
        "Generated by `swift run swift-impact-conformance` from `Conformance/Results`; don't edit.",
        "",
        "Each cell gives a case's outcome in an environment and mode, then its units changed / "
            + "selected / total:",
        "- ✅ every unit that changed was selected;",
        "- ⚠️ only units the case lists as a known gap escaped;",
        "- ❌ a unit changed and wasn't selected;",
        "- ❗ a unit listed as a known gap no longer escapes;",
        "- 🔀 the incremental build after the edit differs from a clean one.",
        "",
        header,
        rule,
    ]
    for testCase in cases {
        var row = "| `\(testCase.name)` | \(testCase.manifest.summary) |"
        for environment in environments {
            let result = results[environment]?.cases[testCase.name]
            for mode in Mode.allCases {
                guard let units = result?.units[mode] else {
                    row += " — |"
                    continue
                }
                let verdict = Verdict(units, mode: mode, manifest: testCase.manifest)
                row += " \(verdict.cell)\(result!.divergent.isEmpty ? "" : " 🔀") |"
            }
        }
        lines.append(row)
    }
    return lines.joined(separator: "\n") + "\n"
}
